static const struct kde_output_configuration_v2_listener kde_cfg_listener = {
    .applied = kde_applied,
    .failed = kde_failed,
    .failure_reason = kde_failure_reason,
};


/* Primary first; the others keep the order the user gave them */
static gint compare_priority(gconstpointer a, gconstpointer b,
                             gpointer data)
{
    WlPriv *p = data;
    const DcOutput *x = a, *y = b;
    WlHead *hx, *hy;
    guint px, py;

    if (x->primary != y->primary) {
        return x->primary ? -1 : 1;
    }
    hx = live_head(p, x);
    hy = live_head(p, y);
    px = (hx && hx->priority >= 0) ? (guint) hx->priority : G_MAXUINT;
    py = (hy && hy->priority >= 0) ? (guint) hy->priority : G_MAXUINT;
    return px < py ? -1 : px > py;
}


static gboolean kde_apply(DcBackend *b, GList *outputs, gboolean persistent,
                          GError **error)
{
    WlPriv *p = b->priv;
    struct kde_output_configuration_v2 *cfg;
    GList *l, *order;
    guint32 prio = 1;
    gboolean ok;

    if (p->dead) {
        g_set_error_literal(error, G_IO_ERROR, G_IO_ERROR_CLOSED,
                            "Lost the connection to the compositor.");
        return FALSE;
    }

    cfg = kde_output_management_v2_create_configuration(p->kde_mgmt);
    kde_output_configuration_v2_add_listener(cfg, &kde_cfg_listener, p);
    reset_result(p);

    for (l = outputs; l; l = l->next) {
        DcOutput *o = l->data;
        WlHead *h = live_head(p, o);
        struct kde_output_device_v2 *dev = h ? h->proxy : NULL;

        if (!dev) continue;
        kde_output_configuration_v2_enable(cfg, dev, o->enabled);
        if (!o->enabled) continue;
        if (o->current_mode >= 0) {
            DcOutputMode *m = &g_array_index(o->modes, DcOutputMode,
                                             o->current_mode);
            gpointer mode = live_mode(h, m);
            if (mode) {
                kde_output_configuration_v2_mode(cfg, dev, mode);
            }
        }
        kde_output_configuration_v2_transform(cfg, dev, o->transform);
        kde_output_configuration_v2_position(cfg, dev, o->x, o->y);
        kde_output_configuration_v2_scale(cfg, dev,
                                          wl_fixed_from_double(o->scale));
        if (o->vrr != DC_VRR_UNSUPPORTED) {
            kde_output_configuration_v2_set_vrr_policy(cfg, dev, o->vrr);
        }
    }

    /* Primary output: priority 1 (Plasma 6), or the older request */
    order = g_list_sort_with_data(g_list_copy(outputs), compare_priority, p);
    for (l = order; l; l = l->next) {
        DcOutput *o = l->data;
        WlHead *h = live_head(p, o);
        if (!h || !o->enabled) continue;
        if (p->kde_mgmt_version >= 3) {
            kde_output_configuration_v2_set_priority(cfg, h->proxy, prio++);
        } else if (p->kde_mgmt_version >= 2 && o->primary) {
            kde_output_configuration_v2_set_primary_output(cfg, h->proxy);
        }
    }
    g_list_free(order);

    kde_output_configuration_v2_apply(cfg);
    ok = wait_result(p, error);
    kde_output_configuration_v2_destroy(cfg);
    wl_display_flush(p->dpy);
    return ok;
}


DcBackend *dc_backend_kde_new(void)
{
    WlPriv *p = wl_connect(&kde_registry_listener);
    DcBackend *b;
    GList *l;

    if (!p) {
        return NULL;
    }
    p->destroy_mode = kde_destroy_mode;
    if (!p->kde_mgmt ||
        (!p->kde_devreg_name && !p->kde_device_globals)) {
        wl_disconnect(p);
        return NULL;
    }

    /* KWin 6.4+ lists devices through a registry; older ones publish one
     * global per device. */
    if (p->kde_devreg_name) {
        p->kde_devreg = wl_registry_bind(p->registry, p->kde_devreg_name,
                                         &kde_output_device_registry_v2_interface,
                                         p->kde_devreg_version);
        kde_output_device_registry_v2_add_listener(p->kde_devreg,
                                                   &kde_devreg_listener, p);
    } else {
        for (l = p->kde_device_globals; l; l = l->next) {
            guint64 g = *(guint64 *) l->data;
            kde_add_device(p, wl_registry_bind(p->registry, g >> 32,
                                               &kde_output_device_v2_interface,
                                               (guint32) g), g >> 32);
        }
    }
    /* registry -> devices -> modes */
    wl_display_roundtrip(p->dpy);
    wl_display_roundtrip(p->dpy);
    wl_display_roundtrip(p->dpy);

    b = g_new0(DcBackend, 1);
    b->name = "KDE output management (Wayland)";
    b->caps = DC_CAP_ANY_SCALE | DC_CAP_DISABLE | DC_CAP_LOGICAL_LAYOUT |
              DC_CAP_SAVED_BY_COMPOSITOR;
    if (p->kde_mgmt_version >= 2) {
        b->caps |= DC_CAP_PRIMARY;
    }
    b->query = wl_query;
    b->apply = kde_apply;
    b->priv = p;
    p->backend = b;
    p->ready = TRUE;
    wl_watch(p);
    return b;
}


