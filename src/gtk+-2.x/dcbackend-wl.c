/* ---- common ------------------------------------------------------------- */

/*
 * Heads and modes are freed as soon as the compositor says they are gone,
 * after destroying their proxies so no further events reach them.  Each
 * gets a unique id: snapshots handed out earlier identify objects by proxy
 * address and id, so a new object at a reused address is not mistaken for
 * the old one.
 */

typedef struct _WlHead WlHead;

typedef struct {
    gpointer proxy;
    guint id;
    WlHead *head;
    gint width, height;
    gint refresh_mhz;
    gboolean preferred;
} WlMode;

struct _WlHead {
    gpointer proxy;
    guint id;
    gchar *name, *make, *model, *serial, *description;
    gint x, y, transform;
    gdouble scale;
    gboolean enabled;
    GPtrArray *modes;        /* WlMode*, owned */
    WlMode *current;
    gint vrr;                /* DcVrr */
    guint vrr_policies;
    gint priority;           /* KDE; -1 unknown */
    guint32 global_name;     /* KDE before the device registry; else 0 */
    gpointer listener_data;  /* owned listener data (KDE), or NULL */
    struct _WlPriv *owner;
};

typedef struct _WlPriv {
    struct wl_display *dpy;
    struct wl_registry *registry;
    DcBackend *backend;
    GList *heads;            /* WlHead* */
    gboolean ready;          /* initial state received */
    gboolean dead;

    /* apply result */
    gboolean result_done, result_ok;
    gchar *result_reason;

    /* KDE */
    struct kde_output_management_v2 *kde_mgmt;
    guint kde_mgmt_version;
    struct kde_output_device_registry_v2 *kde_devreg;
    guint32 kde_devreg_name, kde_devreg_version;
    GList *kde_device_globals;   /* (name << 32 | version) as guint64* */

    /* wlroots */
    struct zwlr_output_manager_v1 *wlr_mgr;
    guint32 wlr_serial;

    /* destroys a mode proxy the right way for its protocol version */
    void (*destroy_mode)(gpointer proxy);
} WlPriv;

static guint next_id = 1;


static WlMode *mode_new(WlHead *h, gpointer proxy)
{
    WlMode *m = g_new0(WlMode, 1);
    m->proxy = proxy;
    m->id = next_id++;
    m->head = h;
    g_ptr_array_add(h->modes, m);
    return m;
}


/* The compositor removed a mode: forget it (its proxy is already gone) */
static void mode_forget(WlMode *m)
{
    WlHead *h = m->head;
    if (h->current == m) {
        h->current = NULL;
    }
    g_ptr_array_remove(h->modes, m);
}


static WlMode *mode_find(WlHead *h, gpointer proxy)
{
    guint i;
    for (i = 0; i < h->modes->len; i++) {
        WlMode *m = g_ptr_array_index(h->modes, i);
        if (m->proxy == proxy) return m;
    }
    return NULL;
}


static WlHead *head_new(WlPriv *p, gpointer proxy)
{
    WlHead *h = g_new0(WlHead, 1);
    h->proxy = proxy;
    h->id = next_id++;
    h->owner = p;
    h->scale = 1.0;
    h->vrr = DC_VRR_UNSUPPORTED;
    h->priority = -1;
    h->modes = g_ptr_array_new_with_free_func(g_free);
    p->heads = g_list_append(p->heads, h);
    return h;
}


/* Free a head whose proxy has been destroyed; destroys its mode proxies */
static void head_free(WlPriv *p, WlHead *h)
{
    guint i;

    for (i = 0; p->destroy_mode && i < h->modes->len; i++) {
        WlMode *m = g_ptr_array_index(h->modes, i);
        p->destroy_mode(m->proxy);
    }
    g_free(h->listener_data);
    g_free(h->name);
    g_free(h->make);
    g_free(h->model);
    g_free(h->serial);
    g_free(h->description);
    g_ptr_array_free(h->modes, TRUE);
    g_free(h);
}


static void set_str(gchar **dst, const char *s)
{
    g_free(*dst);
    *dst = (s && *s) ? g_strdup(s) : NULL;
}


static void changed(WlPriv *p)
{
    if (p->ready && p->backend) {
        dc_backend_notify_changed(p->backend);
    }
}


static GList *heads_to_outputs(WlPriv *p)
{
    GList *ret = NULL, *l;
    gint best_priority = G_MAXINT;

    for (l = p->heads; l; l = l->next) {
        WlHead *h = l->data;
        if (h->enabled && h->priority >= 0) {
            best_priority = MIN(best_priority, h->priority);
        }
    }

    for (l = p->heads; l; l = l->next) {
        WlHead *h = l->data;
        DcOutput *o;
        guint i;

        if (!h->name) continue;
        o = g_new0(DcOutput, 1);
        o->name = g_strdup(h->name);
        o->make = g_strdup(h->make);
        o->model = g_strdup(h->model);
        o->serial = g_strdup(h->serial);
        o->description = g_strdup(h->description);
        o->enabled = h->enabled;
        o->x = h->x;
        o->y = h->y;
        o->scale = h->scale > 0 ? h->scale : 1.0;
        o->transform = h->transform & 7;
        o->primary = h->enabled && h->priority >= 0 &&
                     h->priority == best_priority;
        o->vrr = h->vrr;
        o->vrr_policies = h->vrr_policies;
        o->handle = h->proxy;
        o->handle_id = h->id;
        o->current_mode = -1;
        o->modes = g_array_new(FALSE, FALSE, sizeof(DcOutputMode));

        for (i = 0; i < h->modes->len; i++) {
            WlMode *m = g_ptr_array_index(h->modes, i);
            DcOutputMode dm = { 0 };

            if (m->width <= 0 || m->height <= 0) continue;
            dm.id = g_strdup_printf("%dx%d@%d", m->width, m->height,
                                    m->refresh_mhz);
            dm.width = m->width;
            dm.height = m->height;
            dm.refresh = m->refresh_mhz / 1000.0;
            dm.preferred = m->preferred;
            dm.handle = m->proxy;
            dm.handle_id = m->id;
            g_array_append_val(o->modes, dm);
            if (h->enabled && m == h->current) {
                o->current_mode = o->modes->len - 1;
            }
        }
        ret = g_list_append(ret, o);
    }
    return ret;
}


static gboolean wl_readable(GIOChannel *ch, GIOCondition cond, gpointer data)
{
    WlPriv *p = data;

    if (cond & (G_IO_ERR | G_IO_HUP)) {
        p->dead = TRUE;
        return FALSE;
    }
    /*
     * Never block here: a roundtrip made earlier in this main loop
     * iteration may already have read what woke us up.  read_events()
     * returns at once when there is nothing to read.
     */
    while (wl_display_prepare_read(p->dpy) != 0) {
        if (wl_display_dispatch_pending(p->dpy) < 0) {
            p->dead = TRUE;
            return FALSE;
        }
    }
    if (wl_display_read_events(p->dpy) < 0 ||
        wl_display_dispatch_pending(p->dpy) < 0) {
        p->dead = TRUE;
        return FALSE;
    }
    return TRUE;
}


static void wl_watch(WlPriv *p)
{
    GIOChannel *ch = g_io_channel_unix_new(wl_display_get_fd(p->dpy));
    g_io_add_watch(ch, G_IO_IN | G_IO_ERR | G_IO_HUP, wl_readable, p);
    g_io_channel_unref(ch);
}


/* Wait for the result of an apply request, dispatching other events. */
static gboolean wait_result(WlPriv *p, GError **error)
{
    gint64 deadline = g_get_monotonic_time() + APPLY_TIMEOUT_MS * 1000;
    struct pollfd pfd;

    pfd.fd = wl_display_get_fd(p->dpy);
    pfd.events = POLLIN;

    while (!p->result_done && !p->dead) {
        gint remaining = (deadline - g_get_monotonic_time()) / 1000;
        int r;

        while (wl_display_prepare_read(p->dpy) != 0) {
            wl_display_dispatch_pending(p->dpy);
        }
        if (p->result_done) {
            wl_display_cancel_read(p->dpy);
            break;
        }
        wl_display_flush(p->dpy);
        if (remaining <= 0) {
            wl_display_cancel_read(p->dpy);
            break;
        }
        r = poll(&pfd, 1, remaining);
        if (r <= 0) {
            wl_display_cancel_read(p->dpy);
            if (r < 0 && errno == EINTR) continue;
            break;
        }
        if (wl_display_read_events(p->dpy) < 0 ||
            wl_display_dispatch_pending(p->dpy) < 0) {
            p->dead = TRUE;
        }
    }

    if (!p->result_done) {
        g_set_error_literal(error, G_IO_ERROR, G_IO_ERROR_TIMED_OUT,
                            p->dead ? "Lost the connection to the compositor."
                                    : "The compositor did not answer.");
        return FALSE;
    }
    if (!p->result_ok) {
        g_set_error(error, G_IO_ERROR, G_IO_ERROR_FAILED,
                    "The compositor rejected the configuration%s%s",
                    p->result_reason ? ": " : ".",
                    p->result_reason ? p->result_reason : "");
        return FALSE;
    }
    return TRUE;
}


/* Snapshots handed out earlier may name heads or modes that have gone
 * since; only use objects that are still alive. */
static WlHead *live_head(WlPriv *p, const DcOutput *o)
{
    GList *l;
    for (l = p->heads; l; l = l->next) {
        WlHead *h = l->data;
        if (h->proxy == o->handle && h->id == o->handle_id) return h;
    }
    return NULL;
}


static gpointer live_mode(WlHead *h, const DcOutputMode *m)
{
    guint i;
    for (i = 0; i < h->modes->len; i++) {
        WlMode *mode = g_ptr_array_index(h->modes, i);
        if (mode->proxy == m->handle && mode->id == m->handle_id) {
            return mode->proxy;
        }
    }
    return NULL;
}


/* The output in 'outputs' describing live head 'h', or NULL */
static DcOutput *output_for_head(GList *outputs, WlHead *h)
{
    for (; outputs; outputs = outputs->next) {
        DcOutput *o = outputs->data;
        if (o->handle == h->proxy && o->handle_id == h->id) return o;
    }
    return NULL;
}


static void reset_result(WlPriv *p)
{
    p->result_done = p->result_ok = FALSE;
    g_free(p->result_reason);
    p->result_reason = NULL;
}


static GList *wl_query(DcBackend *b, GError **error)
{
    WlPriv *p = b->priv;

    if (p->dead || wl_display_roundtrip(p->dpy) < 0) {
        p->dead = TRUE;
        g_set_error_literal(error, G_IO_ERROR, G_IO_ERROR_CLOSED,
                            "Lost the connection to the compositor.");
        return NULL;
    }
    return heads_to_outputs(p);
}


static WlPriv *wl_connect(const struct wl_registry_listener *listener)
{
    WlPriv *p;
    struct wl_display *dpy;

    if (!g_getenv("WAYLAND_DISPLAY")) {
        return NULL;
    }
    dpy = wl_display_connect(NULL);
    if (!dpy) {
        return NULL;
    }
    p = g_new0(WlPriv, 1);
    p->dpy = dpy;
    p->registry = wl_display_get_registry(dpy);
    wl_registry_add_listener(p->registry, listener, p);
    wl_display_roundtrip(dpy);
    return p;
}


static void wl_disconnect(WlPriv *p)
{
    GList *l;

    for (l = p->heads; l; l = l->next) {
        head_free(p, l->data);
    }
    g_list_free(p->heads);
    g_list_free_full(p->kde_device_globals, g_free);
    wl_display_disconnect(p->dpy);
    g_free(p->result_reason);
    g_free(p);
}


