static void kde_applied(void *data, struct kde_output_configuration_v2 *c)
{
    WlPriv *p = data;
    p->result_done = p->result_ok = TRUE;
}

static void kde_failed(void *data, struct kde_output_configuration_v2 *c)
{
    WlPriv *p = data;
    p->result_done = TRUE;
    p->result_ok = FALSE;
}

