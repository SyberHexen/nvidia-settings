/* ---- KDE: devices ------------------------------------------------------- */

typedef struct {
    WlPriv *p;
    WlHead *h;
} KdeDev;

#define KH(data) (((KdeDev *) (data))->h)

static void kde_geometry(void *data, struct kde_output_device_v2 *d,
                         int32_t x, int32_t y, int32_t pw, int32_t ph,
                         int32_t subpixel, const char *make,
                         const char *model, int32_t transform)
{
    WlHead *h = KH(data);
    h->x = x;
    h->y = y;
    h->transform = transform;
    set_str(&h->make, make);
    set_str(&h->model, model);
}

static void kde_current_mode(void *data, struct kde_output_device_v2 *d,
                             struct kde_output_device_mode_v2 *mode)
{
    WlHead *h = KH(data);
    h->current = mode_find(h, mode);
}

static void kde_mode(void *data, struct kde_output_device_v2 *d,
                     struct kde_output_device_mode_v2 *mode)
{
    WlMode *m = mode_new(KH(data), mode);
    kde_output_device_mode_v2_add_listener(mode, &kde_mode_listener, m);
}

static void kde_done(void *data, struct kde_output_device_v2 *d)
{
    changed(((KdeDev *) data)->p);
}

static void kde_scale(void *data, struct kde_output_device_v2 *d,
                      wl_fixed_t factor)
{
    KH(data)->scale = wl_fixed_to_double(factor);
}

static void kde_enabled(void *data, struct kde_output_device_v2 *d,
                        int32_t enabled)
{
    KH(data)->enabled = enabled != 0;
}

static void kde_serial(void *data, struct kde_output_device_v2 *d,
                       const char *s)
{
    set_str(&KH(data)->serial, s);
}

static void kde_capabilities(void *data, struct kde_output_device_v2 *d,
                             uint32_t flags)
{
    WlHead *h = KH(data);
    if (flags & KDE_OUTPUT_DEVICE_V2_CAPABILITY_VRR) {
        h->vrr_policies = (1 << DC_VRR_NEVER) | (1 << DC_VRR_ALWAYS) |
                          (1 << DC_VRR_AUTOMATIC);
        if (h->vrr == DC_VRR_UNSUPPORTED) {
            h->vrr = DC_VRR_NEVER;
        }
    } else {
        h->vrr_policies = 0;
        h->vrr = DC_VRR_UNSUPPORTED;
    }
}

static void kde_vrr_policy(void *data, struct kde_output_device_v2 *d,
                           uint32_t policy)
{
    WlHead *h = KH(data);
    if (h->vrr_policies) {
        h->vrr = policy == KDE_OUTPUT_DEVICE_V2_VRR_POLICY_ALWAYS
                 ? DC_VRR_ALWAYS
                 : policy == KDE_OUTPUT_DEVICE_V2_VRR_POLICY_AUTOMATIC
                 ? DC_VRR_AUTOMATIC : DC_VRR_NEVER;
    }
}

static void kde_name(void *data, struct kde_output_device_v2 *d,
                     const char *name)
{
    set_str(&KH(data)->name, name);
}

static void kde_priority(void *data, struct kde_output_device_v2 *d,
                         uint32_t priority)
{
    KH(data)->priority = priority;
}

static void kde_forget_device(WlPriv *p, WlHead *h)
{
    struct kde_output_device_v2 *d = h->proxy;

    if (kde_output_device_v2_get_version(d) >=
        KDE_OUTPUT_DEVICE_V2_RELEASE_SINCE_VERSION) {
        kde_output_device_v2_release(d);
    } else {
        kde_output_device_v2_destroy(d);
    }
    p->heads = g_list_remove(p->heads, h);
    head_free(p, h);
    changed(p);
}

static void kde_removed(void *data, struct kde_output_device_v2 *d)
{
    KdeDev *kd = data;
    kde_forget_device(kd->p, kd->h);
}

