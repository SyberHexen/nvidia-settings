static void wlr_mode_size(void *data, struct zwlr_output_mode_v1 *m,
                          int32_t w, int32_t h)
{
    WlMode *mode = data;
    mode->width = w;
    mode->height = h;
}

static void wlr_mode_refresh(void *data, struct zwlr_output_mode_v1 *m,
                             int32_t refresh)
{
    ((WlMode *) data)->refresh_mhz = refresh;
}

static void wlr_mode_preferred(void *data, struct zwlr_output_mode_v1 *m)
{
    ((WlMode *) data)->preferred = TRUE;
}

static void wlr_destroy_mode(gpointer proxy)
{
    struct zwlr_output_mode_v1 *m = proxy;
    if (zwlr_output_mode_v1_get_version(m) >=
        ZWLR_OUTPUT_MODE_V1_RELEASE_SINCE_VERSION) {
        zwlr_output_mode_v1_release(m);
    } else {
        zwlr_output_mode_v1_destroy(m);
    }
}

static void wlr_mode_finished(void *data, struct zwlr_output_mode_v1 *m)
{
    wlr_destroy_mode(m);
    mode_forget(data);
}

static const struct zwlr_output_mode_v1_listener wlr_mode_listener = {
    .size = wlr_mode_size,
    .refresh = wlr_mode_refresh,
    .preferred = wlr_mode_preferred,
    .finished = wlr_mode_finished,
};


