static void kde_global(void *data, struct wl_registry *reg, uint32_t name,
                       const char *iface, uint32_t version)
{
    WlPriv *p = data;

    if (strcmp(iface, kde_output_management_v2_interface.name) == 0) {
        p->kde_mgmt_version = MIN(version, KDE_MANAGEMENT_VERSION);
        p->kde_mgmt = wl_registry_bind(reg, name,
                                       &kde_output_management_v2_interface,
                                       p->kde_mgmt_version);
    } else if (strcmp(iface,
                      kde_output_device_registry_v2_interface.name) == 0 &&
               version >= KDE_REGISTRY_MIN) {
        p->kde_devreg_name = name;
        p->kde_devreg_version = MIN(version, KDE_DEVICE_VERSION);
    } else if (strcmp(iface, kde_output_device_v2_interface.name) == 0) {
        guint64 *g = g_new(guint64, 1);
        *g = ((guint64) name << 32) | MIN(version, KDE_DEVICE_VERSION);
        p->kde_device_globals = g_list_append(p->kde_device_globals, g);
        /* hotplug after start up (older KWin) */
        if (p->ready && !p->kde_devreg) {
            kde_add_device(p, wl_registry_bind(reg, name,
                                               &kde_output_device_v2_interface,
                                               (guint32) *g), name);
        }
    }
}

/* Before the device registry, an unplugged device only loses its global */
static void kde_global_remove(void *data, struct wl_registry *reg,
                              uint32_t name)
{
    WlPriv *p = data;
    GList *l;

    for (l = p->kde_device_globals; l; l = l->next) {
        if ((*(guint64 *) l->data >> 32) == name) {
            g_free(l->data);
            p->kde_device_globals =
                g_list_delete_link(p->kde_device_globals, l);
            break;
        }
    }
    for (l = p->heads; l; l = l->next) {
        WlHead *h = l->data;
        if (h->global_name == name) {
            kde_forget_device(p, h);
            break;
        }
    }
}


static void noop_global_remove(void *data, struct wl_registry *reg,
                               uint32_t name)
{
}

static const struct wl_registry_listener kde_registry_listener = {
    .global = kde_global,
    .global_remove = kde_global_remove,
};


