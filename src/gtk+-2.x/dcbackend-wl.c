static void wlr_mgr_head(void *data, struct zwlr_output_manager_v1 *mgr,
                         struct zwlr_output_head_v1 *head)
{
    WlPriv *p = data;
    WlHead *h = head_new(p, head);

    /* The protocol cannot tell whether a display supports adaptive sync;
     * version 4 compositors at least let us ask for it. */
    if (zwlr_output_manager_v1_get_version(mgr) >= 4) {
        h->vrr = DC_VRR_NEVER;
        h->vrr_policies = (1 << DC_VRR_NEVER) | (1 << DC_VRR_ALWAYS);
    }
    zwlr_output_head_v1_add_listener(head, &wlr_head_listener, h);
}

static void wlr_mgr_done(void *data, struct zwlr_output_manager_v1 *mgr,
                         uint32_t serial)
{
    WlPriv *p = data;
    p->wlr_serial = serial;
    changed(p);
}

static void wlr_mgr_finished(void *data, struct zwlr_output_manager_v1 *mgr)
{
    ((WlPriv *) data)->dead = TRUE;
}

static const struct zwlr_output_manager_v1_listener wlr_mgr_listener = {
    .head = wlr_mgr_head,
    .done = wlr_mgr_done,
    .finished = wlr_mgr_finished,
};


static void wlr_global(void *data, struct wl_registry *reg, uint32_t name,
                       const char *iface, uint32_t version)
{
    WlPriv *p = data;

    if (strcmp(iface, zwlr_output_manager_v1_interface.name) == 0 &&
        !p->wlr_mgr) {
        p->wlr_mgr = wl_registry_bind(reg, name,
                                      &zwlr_output_manager_v1_interface,
                                      MIN(version, WLR_MANAGER_VERSION));
        zwlr_output_manager_v1_add_listener(p->wlr_mgr, &wlr_mgr_listener, p);
    }
}

static const struct wl_registry_listener wlr_registry_listener = {
    .global = wlr_global,
    .global_remove = noop_global_remove,
};


