static void kde_mode_size(void *data, struct kde_output_device_mode_v2 *m,
                          int32_t w, int32_t h)
{
    WlMode *mode = data;
    mode->width = w;
    mode->height = h;
}

static void kde_mode_refresh(void *data, struct kde_output_device_mode_v2 *m,
                             int32_t refresh)
{
    ((WlMode *) data)->refresh_mhz = refresh;
}

static void kde_mode_preferred(void *data,
                               struct kde_output_device_mode_v2 *m)
{
    ((WlMode *) data)->preferred = TRUE;
}

static void kde_destroy_mode(gpointer proxy)
{
    struct kde_output_device_mode_v2 *m = proxy;
    if (kde_output_device_mode_v2_get_version(m) >=
        KDE_OUTPUT_DEVICE_MODE_V2_RELEASE_SINCE_VERSION) {
        kde_output_device_mode_v2_release(m);
    } else {
        kde_output_device_mode_v2_destroy(m);
    }
}

static void kde_mode_removed(void *data, struct kde_output_device_mode_v2 *m)
{
    kde_destroy_mode(m);
    mode_forget(data);
}

